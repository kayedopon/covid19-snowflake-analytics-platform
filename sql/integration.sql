CREATE SCHEMA IF NOT EXISTS COVID_ANALYTICS.ANALYTICS;

-- creating a view based on JHU_COVID_19 but with different granularity
CREATE OR REPLACE VIEW ANALYTICS.COVID_YEARLY AS
SELECT
    COUNTRY_REGION,
    YEAR(DATE) AS YEAR,
    SUM(
        CASE
            WHEN CASE_TYPE = 'Confirmed' THEN DIFFERENCE
            ELSE 0
        END
    ) AS CONFIRMED_CASES,
    SUM(
        CASE
            WHEN CASE_TYPE = 'Deaths' THEN DIFFERENCE
            ELSE 0
        END
    ) AS DEATHS
FROM COVID19_EPIDEMIOLOGICAL_DATA.PUBLIC.JHU_COVID_19
WHERE YEAR(DATE) BETWEEN 2020 AND 2023
GROUP BY
    COUNTRY_REGION,
    YEAR(DATE);

-- investigate new view
