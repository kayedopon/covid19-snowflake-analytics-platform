SELECT
    DATE,
    CASES,
    DIFFERENCE
FROM JHU_COVID_19
WHERE COUNTRY_REGION = 'Argentina'
  AND CASE_TYPE = 'Recovered'
ORDER BY DATE DESC
LIMIT 30;

SELECT
    COUNTRY_REGION,
    SUM(DIFFERENCE) AS total_recovered
FROM JHU_COVID_19
WHERE CASE_TYPE = 'Recovered'
  AND DIFFERENCE > 0
GROUP BY COUNTRY_REGION
ORDER BY total_recovered DESC
LIMIT 20;

-- total confirmed cases by month
SELECT
    DATE_TRUNC('MONTH', DATE) AS month,
    SUM(DIFFERENCE) AS new_cases
FROM JHU_COVID_19
WHERE CASE_TYPE = 'Confirmed'
GROUP BY month
ORDER BY month;

-- rolling mean of new cases
WITH daily_cases AS (
    SELECT
        DATE,
        COUNTRY_REGION,
        SUM(DIFFERENCE) AS new_cases
    FROM JHU_COVID_19
    WHERE CASE_TYPE = 'Confirmed'
    GROUP BY DATE, COUNTRY_REGION
)

SELECT
    DATE,
    COUNTRY_REGION,
    new_cases,
    AVG(new_cases) OVER (
        PARTITION BY COUNTRY_REGION
        ORDER BY DATE
        ROWS BETWEEN 6 PRECEDING AND CURRENT ROW
    ) AS avg_7_day_cases
FROM daily_cases
WHERE COUNTRY_REGION = 'Lithuania'
ORDER BY COUNTRY_REGION, DATE;


-- rolling mean of deaths
WITH daily_cases AS (
    SELECT
        DATE,
        COUNTRY_REGION,
        SUM(DIFFERENCE) AS new_deaths
    FROM JHU_COVID_19
    WHERE CASE_TYPE = 'Deaths'
    GROUP BY DATE, COUNTRY_REGION
)

SELECT
    DATE,
    COUNTRY_REGION,
    new_deaths,
    AVG(new_deaths) OVER (
        PARTITION BY COUNTRY_REGION
        ORDER BY DATE
        ROWS BETWEEN 6 PRECEDING AND CURRENT ROW
    ) AS avg_7_day_deaths
FROM daily_cases
WHERE COUNTRY_REGION = 'Lithuania'
ORDER BY COUNTRY_REGION, DATE;


SELECT
    DATE_TRUNC('MONTH', DATE) AS month,
    SUM(DIFFERENCE) AS new_cases
FROM JHU_COVID_19
WHERE CASE_TYPE = 'Confirmed'
GROUP BY month
ORDER BY month;