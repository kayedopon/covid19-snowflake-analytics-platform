    SUM(DIFFERENCE) AS total_cases
FROM JHU_COVID_19
WHERE CASE_TYPE = 'Deaths'
GROUP BY COUNTRY_REGION
HAVING SUM(DIFFERENCE) IS NOT NULL
ORDER BY total_cases DESC
LIMIT 15;


-- recovered
SELECT
    COUNTRY_REGION,
    SUM(DIFFERENCE) AS total_cases
FROM JHU_COVID_19
WHERE CASE_TYPE = 'Recovered'
GROUP BY COUNTRY_REGION
HAVING SUM(DIFFERENCE) IS NOT NULL
